import os
import re
import subprocess

from color_utils import sanitize_color


def _write(path, content):
    # Older versions symlinked these into ~/.themes/Material-Gnome; replace with real files.
    try:
        if os.path.islink(path):
            os.remove(path)
        with open(path, "w") as f:
            f.write(content)
    except OSError:
        pass


def apply(home, colors):
    """Recolor GTK3/GTK4 through libadwaita named colors on top of adw-gtk3."""
    bg = colors["bg"]
    fg = colors["fg"]
    bg2 = colors["bgSecondary"]
    bg3 = colors.get("bgTertiary", bg2)
    bg_accent = colors.get("bgAccent", bg2)
    accent = colors["accent"]
    border = colors["border"]
    is_dark = colors["is_dark"]

    named = {
        "accent_color": accent,
        "accent_bg_color": accent,
        "accent_fg_color": bg,
        "destructive_color": accent,
        "window_bg_color": bg,
        "window_fg_color": fg,
        "view_bg_color": bg3,
        "view_fg_color": fg,
        "headerbar_bg_color": bg2,
        "headerbar_fg_color": fg,
        "headerbar_border_color": border,
        "headerbar_backdrop_color": bg,
        "card_bg_color": bg2,
        "card_fg_color": fg,
        "dialog_bg_color": bg2,
        "dialog_fg_color": fg,
        "popover_bg_color": bg2,
        "popover_fg_color": fg,
        "sidebar_bg_color": bg2,
        "sidebar_fg_color": fg,
        "sidebar_backdrop_color": bg,
        "sidebar_border_color": border,
        "secondary_sidebar_bg_color": bg3,
        "secondary_sidebar_fg_color": fg,
        "thumbnail_bg_color": bg_accent,
        "thumbnail_fg_color": fg,
    }
    css = "/* Generated by Quickshell theme service (adw-gtk3) */\n"
    for k, v in named.items():
        css += f"@define-color {k} {sanitize_color(v)};\n"

    for d in ("gtk-3.0", "gtk-4.0"):
        os.makedirs(os.path.join(home, ".config", d), exist_ok=True)
        _write(os.path.join(home, ".config", d, "gtk.css"), css)

    theme = "adw-gtk3-dark" if is_dark else "adw-gtk3"
    scheme = "prefer-dark" if is_dark else "prefer-light"
    gs = ["gsettings", "set", "org.gnome.desktop.interface"]
    subprocess.run(gs + ["color-scheme", scheme], stderr=subprocess.DEVNULL)
    subprocess.run(gs + ["gtk-theme", theme], stderr=subprocess.DEVNULL)

    for ini in [
        os.path.join(home, ".config", "gtk-3.0", "settings.ini"),
        os.path.join(home, ".config", "gtk-4.0", "settings.ini"),
    ]:
        if os.path.exists(ini):
            try:
                with open(ini, "r") as f:
                    content = f.read()
                content = re.sub(
                    r"^gtk-theme-name=.*",
                    f"gtk-theme-name={theme}",
                    content,
                    flags=re.MULTILINE,
                )
                with open(ini, "w") as f:
                    f.write(content)
            except Exception:
                pass
    os.system(
        rf"sed -i 's/^Net\/ThemeName.*/Net\/ThemeName \"{theme}\"/' '{home}/.config/xsettingsd/xsettingsd.conf' 2>/dev/null"
    )
    os.system("killall -HUP xsettingsd 2>/dev/null || true")
