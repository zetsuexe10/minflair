import json
import os

from color_utils import sanitize_color
from minflair_paths import ROOT, STATE, XDG


def _write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    try:
        if os.path.islink(path):
            os.remove(path)
        with open(path, "w") as f:
            f.write(content)
    except OSError:
        pass


def _settings_ini(path, theme, extra):
    """Rewrite only the keys we own, keep any others already in the file."""
    keys = {"gtk-theme-name": theme, "gtk-application-prefer-dark-theme": extra["dark"]}
    if extra.get("font"):
        keys["gtk-font-name"] = extra["font"]
    if extra.get("cursor"):
        keys["gtk-cursor-theme-name"] = extra["cursor"]
    if extra.get("icon"):
        keys["gtk-icon-theme-name"] = extra["icon"]
    if extra.get("cursor_size"):
        keys["gtk-cursor-theme-size"] = extra["cursor_size"]
    lines, seen = [], set()
    if os.path.exists(path):
        with open(path) as f:
            for line in f.read().splitlines():
                k = line.split("=", 1)[0].strip()
                if k in keys:
                    line = f"{k}={keys[k]}"
                    seen.add(k)
                lines.append(line)
    if not lines:
        lines = ["[Settings]"]
    for k, v in keys.items():
        if k not in seen:
            lines.append(f"{k}={v}")
    _write(path, "\n".join(lines) + "\n")


def apply(home, colors):
    """Recolor GTK3/GTK4 via libadwaita named colors on top of adw-gtk3.

    Output goes to ~/.minflair/xdg/gtk-{3,4}.0 only; no gsettings, no ~/.config.
    """
    bg, fg = colors["bg"], colors["fg"]
    bg2 = colors["bgSecondary"]
    bg3 = colors.get("bgTertiary", bg2)
    bg_accent = colors.get("bgAccent", bg2)
    accent, border = colors["accent"], colors["border"]
    is_dark = colors["is_dark"]

    named = {
        "accent_color": accent, "accent_bg_color": accent, "accent_fg_color": bg,
        "window_bg_color": bg, "window_fg_color": fg,
        "view_bg_color": bg3, "view_fg_color": fg,
        "headerbar_bg_color": bg2, "headerbar_fg_color": fg,
        "headerbar_border_color": border, "headerbar_backdrop_color": bg,
        "card_bg_color": bg2, "card_fg_color": fg,
        "dialog_bg_color": bg2, "dialog_fg_color": fg,
        "popover_bg_color": bg2, "popover_fg_color": fg,
        "sidebar_bg_color": bg2, "sidebar_fg_color": fg,
        "sidebar_backdrop_color": bg, "sidebar_border_color": border,
        "secondary_sidebar_bg_color": bg3, "secondary_sidebar_fg_color": fg,
        "thumbnail_bg_color": bg_accent, "thumbnail_fg_color": fg,
    }
    css = "/* Generated by Quickshell theme service (adw-gtk3) */\n"
    for k, v in named.items():
        css += f"@define-color {k} {sanitize_color(v)};\n"

    theme = "adw-gtk3-dark" if is_dark else "adw-gtk3"
    prev = {}
    try:
        with open(STATE) as f:
            prev = json.load(f)
    except Exception:
        pass
    extra = {
        "dark": "1" if is_dark else "0",
        "font": (f'{prev["gtk_font"]} {prev.get("gtk_font_size", 11)}' if prev.get("gtk_font") else prev.get("font")),
        "cursor": prev.get("cursor"),
        "icon": prev.get("icon_theme"),
        "cursor_size": prev.get("cursor_size"),
    }
    for d in ("gtk-3.0", "gtk-4.0"):
        _write(os.path.join(XDG, d, "gtk.css"), css)
        _settings_ini(os.path.join(XDG, d, "settings.ini"), theme, extra)

    prev.update({"is_dark": bool(is_dark), "gtk_theme": theme})
    os.makedirs(ROOT, exist_ok=True)
    with open(STATE, "w") as f:
        json.dump(prev, f, indent=2)
